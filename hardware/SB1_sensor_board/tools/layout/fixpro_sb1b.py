"""Point the KiCad project file at rev B (2026-10-31): Power net-class patterns for rev B's rails, the USB class
dropped, and the sheet list taken from the root schematic. usage: fixpro_sb1b.py <project dir>"""
import json, re, sys, os
P = sys.argv[1]
pro = os.path.join(P, 'moveOmeter_SB1.kicad_pro')
p = json.load(open(pro))
ns = p['net_settings']
ns['netclass_patterns'] = [{'netclass': 'Power', 'pattern': n}
                           for n in ['+5V', '+5V_6004', '*+5V_2450', '+3V3', '*A_3V3*', '*A_SW', '*B_5V*']]
ns['classes'] = [c for c in ns['classes'] if c['name'] != 'USB']
root = open(os.path.join(P, 'moveOmeter_SB1.kicad_sch')).read()
sheets = re.findall(r'\(sheet \(at [^)]*\) \(size [^)]*\).*?\(uuid "([^"]+)"\) \(property "Sheetname" "([^"]+)"', root)
root_uuid = re.search(r'\(uuid "([^"]+)"\) \(paper', root).group(1)
p['sheets'] = [[root_uuid, 'Root']] + [[u, n] for u, n in sheets]
open(pro, 'w').write(json.dumps(p, indent=2) + '\n')
print('project file updated:', p['sheets'])

# Custom design rules (John, 11/7): power rails at least 0.4 mm wide (Power class asks for 0.5), allowed to neck down
# [11/9: minimum 0.35 mm; Freerouting necks 0.5 mm tracks to 0.375 mm into tight spots, still > 1 A on 1 oz outer]
# to 0.25 mm only where the track meets a fine-pitch part (ZIF pins are 0.4 mm wide, SOT/SOIC pins 0.6 mm). KiCad
# applies the last matching rule, so the exception comes after the general rule. Freerouting does not read this file;
# it uses the Power class width (0.5 mm), and this file makes DRC flag any power track that came out thinner.
FINE = ('J7', 'JP1', 'JP2', 'JP3', 'U1', 'U2', 'U3', 'U4')
near = ' || '.join(f"A.intersectsCourtyard('{r}')" for r in FINE)
open(os.path.join(P, 'moveOmeter_SB1.kicad_dru'), 'w').write(f"""(version 1)

# Generated by tools/layout/fixpro_sb1b.py -- edit there, not here.
(rule "Power tracks at least 0.35 mm"
  (condition "A.NetClass == 'Power'")
  (constraint track_width (min 0.35mm) (opt 0.5mm)))

(rule "No tracks on inner GND plane In1"
  (layer "In1.Cu")
  (constraint disallow track))

(rule "No tracks on inner GND plane In2"
  (layer "In2.Cu")
  (constraint disallow track))

(rule "Power neck-down at fine-pitch pads"
  (condition "A.NetClass == 'Power' && ({near})")
  (constraint track_width (min 0.25mm) (opt 0.5mm)))
""")
# 11/10: the In1 / In2 track ban moved here from a board-wide rule area (KiCad exports rule areas to the DSN, and
# Freerouting treated that one as a keep-out for vias too). Custom rules aren't exported.
print('design rules written: moveOmeter_SB1.kicad_dru')
